FlowerProfileKey flowerProfileKeyFor(String id) {
  switch (id) {
    case 'zonnebloem':
    case 'cosmos':
    case 'zinnia':
    case 'korenbloem':
    case 'klaproos':
    case 'verbena':
    case 'alyssum_sneeuw':
    case 'stiefmoedje':
      return FlowerProfileKey.annualCut;
    case 'afrikaantje':
    case 'tagetes_patula':
    case 'goudsbloem':
    case 'calendula_officinalis':
    case 'ringelbloem':
    case 'oostindische_kers':
      return FlowerProfileKey.companionPest;
    case 'komkommerkruid':
    case 'monarda':
    case 'zonnehoed':
    case 'duizendblad':
    case 'limnanthes':
    case 'bijenmengsel':
      return FlowerProfileKey.pollinator;
    case 'zaadslurf': // Lobularia / alyssum — laag tapijt, zweefvliegen
      return FlowerProfileKey.companionPest;
    case 'facelia':
    case 'boekweit':
    case 'witte_klaver':
    case 'rode_klaver':
    case 'lupine_groenbemester':
    case 'mosterd_geel':
      return FlowerProfileKey.greenManure;
    case 'lavendel':
    case 'hysop':
    case 'wilde_marjolein':
    case 'tijm_bloei':
    case 'salie_bloei':
      return FlowerProfileKey.mediterranean;
    case 'ui_bloei':
    case 'look_bloei':
    case 'dille_bloei':
    case 'koriander_bloei':
    case 'basilicum_bloei':
    case 'munt_bloei':
      return FlowerProfileKey.herbBloom;
    case 'lindebloesem':
      return FlowerProfileKey.treeBloom;
    default:
      return FlowerProfileKey.annualCut;
  }
}

FlowerGuideProfile flowerGuideProfileFor(String id) {
  final base = kFlowerProfiles[flowerProfileKeyFor(id)]!;
  final o = _kFlowerOverrides[id];
  if (o == null) return base;
  return _merge(base, o);
}

