VegetableImageInfo vegetableImageFor(String vegetableId) {
  final canonicalId = normalizeVegetableId(vegetableId);
  final mapped =
      kVegetableImages[canonicalId] ?? kVegetableImages[vegetableId];
  if (mapped?.assetPath != null) {
    return mapped!;
  }

  final VegetableImageInfo base;
  final companionEmoji =
      kMoestuinCompanionEmojis[canonicalId] ?? kMoestuinCompanionEmojis[vegetableId];
  if (companionEmoji != null) {
    base = VegetableImageInfo(emoji: companionEmoji, greenBackground: false);
  } else {
    final bulkEmoji =
        kNlCommonPlantEmojis[canonicalId] ??
        kNlCommonPlantEmojis[vegetableId] ??
        kNewGardenVarietyEmojis[canonicalId] ??
        kNewGardenVarietyEmojis[vegetableId];
    if (bulkEmoji != null) {
      base = VegetableImageInfo(emoji: bulkEmoji, greenBackground: true);
    } else {
      base = mapped ?? _defaultInfo;
    }
  }
  if (!kAtlasIconsForAllPlants) return base;
  return _withAtlasAsset(base, vegetableId);
}
