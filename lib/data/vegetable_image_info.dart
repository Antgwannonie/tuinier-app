  groundShadow: false,
);

VegetableImageInfo _withAtlasAsset(VegetableImageInfo base, String vegetableId) {
  return VegetableImageInfo(
    emoji: base.emoji,
    imageUrl: base.imageUrl,
    assetPath: 'assets/images/vegetables/$vegetableId.png',
    greenBackground: false,
    transparentAsset: true,
    atlasIllustrationScale: base.atlasIllustrationScale != 1.0
        ? base.atlasIllustrationScale
        : _atlasDefaults.illustrationScale,
    atlasRecessDisc: base.atlasRecessDisc || _atlasDefaults.recessDisc,
    atlasGroundShadow: base.atlasGroundShadow,
  );
}

