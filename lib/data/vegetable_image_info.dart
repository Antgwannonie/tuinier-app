/// Afbeelding / emoji per groente-id (offline emoji + optionele foto-URL).
class VegetableImageInfo {
  const VegetableImageInfo({
    required this.emoji,
    this.imageUrl,
    this.assetPath,
    this.greenBackground = true,
    this.transparentAsset = false,
    this.atlasIllustrationScale = 1.0,
    this.atlasGroundShadow = false,
    this.atlasRecessDisc = false,
    this.atlasCardCover = false,
    this.atlasCardAlignY = 0,
    this.atlasCardPrecropped = false,
    this.thumbnailScale = 1.0,
  });

  final String emoji;
  final String? imageUrl;

  /// Lokaal icoon (assets/) voor zoek- en detailpagina.
  final String? assetPath;

  /// Groene (#E8F5E9) of witte achtergrond (niet bij [transparentAsset]).
  final bool greenBackground;

  /// PNG zonder wit vlak — kaartkleur schijnt door (Zoeken/detail).
  final bool transparentAsset;

  /// Vergroot illustratie op atlas-kaarten (bijv. 1.35).
  final double atlasIllustrationScale;

  /// Zachte ovale schaduw onder de plant (als PNG geen schijf heeft).
  final bool atlasGroundShadow;

  /// Donkere cirkel onder de plant (zoals atlas-sidebar iconen).
  final bool atlasRecessDisc;

  /// Kaart-PNG met achtergrond — vult Zoeken-kaart / detail-balk.
  final bool atlasCardCover;

  /// Verticale focus (-1 boven … 1 onder).
  final double atlasCardAlignY;

  /// PNG is al 512×826 (Zoeken-kaart) — vult kaart zonder tweede crop.
  final bool atlasCardPrecropped;

  /// Vergroot icoon in Zoeken-thumbnail (bijv. 1.2).
  final double thumbnailScale;
}

