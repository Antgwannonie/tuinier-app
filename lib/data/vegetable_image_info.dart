VegetableImageInfo vegetableImageFor(String vegetableId) {
  final mapped = kVegetableImages[vegetableId];
  if (mapped?.assetPath != null) {
    return mapped!;
  }

  final VegetableImageInfo base;
  final companionEmoji = kMoestuinCompanionEmojis[vegetableId];
  if (companionEmoji != null) {
    base = VegetableImageInfo(emoji: companionEmoji, greenBackground: false);
  } else {
    final bulkEmoji = kNlCommonPlantEmojis[vegetableId];
    if (bulkEmoji != null) {
      base = VegetableImageInfo(emoji: bulkEmoji, greenBackground: true);
    } else {
      base = mapped ?? _defaultInfo;
    }
  }
  if (!kAtlasIconsForAllPlants) return base;
  return _withAtlasAsset(base, vegetableId);
}
